def _append(path, fields, row):
    new = not Path(path).exists()
    with open(path, "a", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        if new:
            w.writeheader()
        w.writerow(row)
        f.flush()
        os.fsync(f.fileno())


def _utc():
    return datetime.datetime.now(datetime.timezone.utc).isoformat()


def run_quality(pipe, todo_items, conds, out_dir, csv_name="swap.csv", reproduce=False):
    path = Path(out_dir) / csv_name
    done = rf.done_keys(path, 1)
    stored = load_stored()
    todo = [(it, c) for it in todo_items for c in conds if (it["utt_id"], c) not in done]
    print(f"[quality] {len(todo)} cases to run ({len(done)} already in {path.name}) on {pipe.gpu}", flush=True)
    taus, repro = list(pipe.sampler.STUDENT_TAUS), []
    for n, (item, cond) in enumerate(todo, 1):
        t0 = time.perf_counter()
        ctx = pipe.prepare(item, cond, item["input_seed"], out_dir)
        E, _ = pipe.teacher(ctx, (K,))
        S = student_sample(pipe, ctx)
        with pipe.torch.inference_mode():
            inputs = handover_inputs(E, S, ctx["prompt_len"], OUTS)
            rms = swap_rms(E[K], S, ctx["prompt_len"])
        gt = pipe.ground_truth(item)
        row = {"utt_id": item["utt_id"], "speaker_id": item["speaker_id"], "condition": cond, "prompt_snr": ctx["prompt_snr"],
               "gpu": pipe.gpu, "swap_rms": rms}
        for o in OUTS:
            m = pipe.score(ng.decode(pipe, ctx, gl.student(pipe, ctx, inputs[o], taus)), item, gt)
            row.update({f"{k}_{o}": m[k] for k in METRICS + ("hypothesis",)})
        if reproduce:
            E8, _ = pipe.teacher(ctx, (8,))
            for k, T in ((K, E[K]), (8, E8[8])):
                m = pipe.score(ng.decode(pipe, ctx, gl.student(pipe, ctx, T, taus)), item, gt)
                s = stored[(item["utt_id"], cond)]["m"][f"plain_{k}"]
                repro.append({"utt_id": item["utt_id"], "condition": cond, "step": k, "wer": m["wer"], "wer_stored": s["wer"],
                              "similarity": m["similarity"], "similarity_stored": s["similarity"]})
        row.update({"case_seconds": round(time.perf_counter() - t0, 2), "utc": _utc()})
        _append(path, FIELDS, row)
        print(f"[{n}/{len(todo)}] quality: {item['utt_id']} {cond} ({row['case_seconds']:.0f} s)", flush=True)
    print(f"[OK] quality complete: {path}", flush=True)
    return repro


def run_diversity(pipe, pairs, out_dir, seeds=DIV_SEEDS, csv_name="diversity.csv"):
    path = Path(out_dir) / csv_name
    done = rf.done_keys(path, 1)
    todo = [it for it in pairs if (it["utt_id"], "clean") not in done]
    print(f"[diversity] {len(todo)} pairs x {seeds} seeds to run ({len(done)} already in {path.name})", flush=True)
    taus = list(pipe.sampler.STUDENT_TAUS)
    for n, item in enumerate(todo, 1):
        t0 = time.perf_counter()
        tracks = {o: [] for o in DIV_OUTS}
        for m in range(seeds):
            ctx = pipe.prepare(item, "clean", int(item["input_seed"]) + DIV_SEED_BASE + m, out_dir, noise_seed=item["input_seed"])
            E, _ = pipe.teacher(ctx, (K, 8))
            S = student_sample(pipe, ctx)
            with pipe.torch.inference_mode():
                inputs = handover_inputs(E, S, ctx["prompt_len"], [o for o in DIV_OUTS if o != "student4"])
            for o in DIV_OUTS:
                x = gl.student(pipe, ctx, ctx["step_cond"], [0.0] + taus) if o == "student4" else gl.student(pipe, ctx, inputs[o], taus)
                tracks[o].append(f0_track(ng.decode(pipe, ctx, x)))
        row = {"utt_id": item["utt_id"], "speaker_id": item["speaker_id"], "condition": "clean", "n_seeds": seeds}
        for o in DIV_OUTS:
            row[f"cvf0_{o}"], row[f"voiced_{o}"] = cvf0(tracks[o])
        row.update({"case_seconds": round(time.perf_counter() - t0, 2), "utc": _utc()})
        _append(path, DIV_FIELDS, row)
        print(f"[{n}/{len(todo)}] diversity: {item['utt_id']} ({row['case_seconds']:.0f} s)", flush=True)
    print(f"[OK] diversity complete: {path}", flush=True)


