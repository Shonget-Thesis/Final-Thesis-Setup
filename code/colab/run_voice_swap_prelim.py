def freeze(out=EXP_DIR):
    path = Path(out) / "preregistration.json"
    Path(out).mkdir(parents=True, exist_ok=True)
    if path.exists():
        raise SystemExit(f"{path} exists; a preregistration is written once (delete it only if nothing was synthesized)")
    pre = build_prereg()
    pre["sha256"] = hashlib.sha256(json.dumps(pre, sort_keys=True).encode("utf-8")).hexdigest()
    pre["created_utc"] = _utc()
    path.write_text(json.dumps(pre, indent=2) + "\n", encoding="utf-8")
    print(f"[OK] preregistration written: {path} (sha256 {pre['sha256'][:16]}...)", flush=True)
    return pre


def check_prereg(prereg_path=PREREG_PATH):
    p = Path(prereg_path)
    if not p.exists():
        raise SystemExit(f"Missing {p}: run `freeze` and push the preregistration before any GPU run.")
    pre = json.loads(p.read_text(encoding="utf-8"))
    body = {k: v for k, v in pre.items() if k not in ("sha256", "created_utc")}
    if hashlib.sha256(json.dumps(body, sort_keys=True).encode("utf-8")).hexdigest() != pre["sha256"]:
        raise SystemExit("preregistration.json was edited after it was frozen")
    if pre["runner_sha256"] != sha256_text(Path(__file__)):
        raise SystemExit("This runner differs from the one frozen in preregistration.json")
    return pre


def check_reproduction(repro, tolerance=REPRODUCTION_TOLERANCE):
    """The analysis reuses stored labels, so this runner must reproduce them; returns the largest differences."""
    worst_wer = max(abs(r["wer"] - r["wer_stored"]) for r in repro)
    worst_sim = max(abs(r["similarity"] - r["similarity_stored"]) for r in repro)
    if worst_wer > tolerance or worst_sim > tolerance:
        raise SystemExit(f"Stored labels not reproduced (max |dWER| {worst_wer:.4f}, max |dSIM| {worst_sim:.4f}). "
                         "Do not run: the stored Step-k and reference outputs cannot be reused on this setup.")
    return worst_wer, worst_sim


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["freeze", "smoke", "run", "analyze"])
    ap.add_argument("--out")
    ap.add_argument("--dmo_root", default="/content/Shonget-DMOSpeech2")
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--allow_partial", action="store_true")
    args = ap.parse_args(argv)
    if args.cmd == "freeze":
        freeze(args.out or EXP_DIR)
        return
    if not args.out:
        ap.error("--out is required")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    if args.cmd == "analyze":
        analyze(out, args.allow_partial)
        return
    check_prereg()
    pipe = rf.Pipeline(args.dmo_root, args.device)
    if "T4" not in pipe.gpu:
        raise SystemExit(f"EXP-020 reuses T4 labels and student noise depends on the GPU; found {pipe.gpu}.")
    if args.cmd == "smoke":
        out = out / "smoke"
        out.mkdir(exist_ok=True)
        its = [it for it in ex.items() if it["utt_id"] not in cg.pilot_utts()][:2]
        repro = run_quality(pipe, its, ("clean", "gauss20"), out, reproduce=True)
        (out / "reproduction.json").write_text(json.dumps(repro, indent=2) + "\n", encoding="utf-8")
        worst_wer, worst_sim = check_reproduction(repro)
        run_diversity(pipe, ex.items()[:1], out, seeds=2)
        print(f"Smoke run complete: {out} (stored labels reproduced: max |dWER| {worst_wer:.4f}, max |dSIM| {worst_sim:.4f})", flush=True)
        return
    smoke_file = out / "smoke" / "reproduction.json"
    if not smoke_file.exists():
        raise SystemExit("Run the smoke test first: the full run reuses stored labels only if they reproduce.")
    check_reproduction(json.loads(smoke_file.read_text(encoding="utf-8")))
    shutil.copy2(PREREG_PATH, out / "preregistration.json")
    run_quality(pipe, ex.items(), CONDS, out)
    run_diversity(pipe, ex.items()[:DIV_PAIRS], out)
    analyze(out)


if __name__ == "__main__":
    main()
