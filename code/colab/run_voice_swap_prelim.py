def load_stored():
    """(utt, cond) -> plain Steps 4 and 8 (EXP-018) and student only (EXP-017), for the 360 development cases."""
    utts = {it["utt_id"] for it in ex.items()}
    grid = {(r["utt_id"], r["condition"]): r for r in rf.read_csv(GRID32_CSV)}
    out = {}
    for r in rf.read_csv(STEPS_CSV):
        key = (r["utt_id"], r["condition"])
        if r["utt_id"] not in utts or r["condition"] not in CONDS or key not in grid:
            continue
        m = {f"plain_{k}": {x: float(r[f"{x}_g16_{k}"]) for x in METRICS} for k in (K, 8)}
        m["student4"] = {x: float(grid[key][f"{x}_student4"]) for x in METRICS}
        out[key] = {"speaker_id": r["speaker_id"], "prompt_snr": float(r["prompt_snr"]), "m": m}
    return out


def build_table(stored, rows, th):
    table = []
    for r in rows:
        s = stored.get((r["utt_id"], r["condition"]))
        if s is None:
            continue
        m = {**s["m"], **{o: {x: float(r[f"{x}_{o}"]) for x in METRICS} for o in OUTS}}
        table.append({"utt": r["utt_id"], "spk": s["speaker_id"], "cond": r["condition"], "snr": s["prompt_snr"], "m": m,
                      "fail": {n: bool(gl.failed(v, m["plain_8"], th)) for n, v in m.items()}})
    return table


def paired_failures(table, a, b, conds):
    rows = sorted((r for r in table if r["cond"] in conds), key=lambda r: (r["utt"], r["cond"]))
    only_a, only_b, p = rf.mcnemar_exact([r["fail"][a] for r in rows], [r["fail"][b] for r in rows])
    return {"n": len(rows), "a": sum(r["fail"][a] for r in rows), "b": sum(r["fail"][b] for r in rows),
            "only_a": only_a, "only_b": only_b, "p": p}


def _boot_ci(groups, B=BOOT_B, seed=SEED):
    """Mean of per-speaker values and its percentile 95% interval, resampling speakers."""
    values = [sum(v) / len(v) for v in groups.values()]
    if not values:
        return {"mean": None, "lo": None, "hi": None}
    rng = random.Random(seed)
    boots = sorted(sum(rng.choice(values) for _ in values) / len(values) for _ in range(B))
    return {"mean": sum(values) / len(values), "lo": boots[int(0.025 * B)], "hi": boots[int(0.975 * B)]}


def metric_diff(table, a, b, metric, conds):
    """Speaker-clustered mean of metric(a) - metric(b); WER is capped at 1 per utterance."""
    cap = (lambda v: min(1.0, v)) if metric == "wer" else (lambda v: v)
    groups = {}
    for r in table:
        if r["cond"] in conds:
            groups.setdefault(r["spk"], []).append(cap(r["m"][a][metric]) - cap(r["m"][b][metric]))
    return _boot_ci(groups)


def cv_diff(div, a, b):
    groups = {r["speaker_id"]: [float(r[f"cvf0_{a}"]) - float(r[f"cvf0_{b}"])] for r in div
              if not (math.isnan(float(r[f"cvf0_{a}"])) or math.isnan(float(r[f"cvf0_{b}"])))}
    return _boot_ci(groups)


def policy(name, p):
    if name == "reference":
        return lambda r: "plain_8"
    if name == "plain4_all":
        return lambda r: "plain_4"
    if name == "vswap_all":
        return lambda r: "vswap_4"
    if name == "snr_theta":
        return lambda r: "plain_4" if r["snr"] >= p else "plain_8"
    if name == "vswap_theta":
        return lambda r: "vswap_4" if r["snr"] >= p else "plain_8"
    if name == "route3":
        hi, lo = p
        return lambda r: "plain_4" if r["snr"] >= hi else ("vswap_4" if r["snr"] >= lo else "plain_8")
    raise ValueError(name)


POLICIES = ["reference", "plain4_all", "vswap_all", "snr_theta", "vswap_theta", "route3"]


def certified(train, pol, delta):
    """Learn-Then-Test binomial tail: the rule's failure rate is below ALPHA at level delta."""
    return rf.binom_cdf(sum(int(r["fail"][pol(r)]) for r in train), len(train), ALPHA) <= delta


def select_single(train, name):
    """Fixed-sequence Learn-Then-Test along one prespecified SNR path, conservative to aggressive."""
    chosen = None
    for p in SNR_GRID:
        if not certified(train, policy(name, p), DELTA):
            break
        chosen = p
    return chosen


def select_route(train):
    """Two cut-offs: one fixed-sequence chain over theta_lo for each prespecified theta_hi, with delta split
    equally across the chains (Bonferroni). The cheapest certified pair on the calibration data is returned."""
    best, best_cost, delta = None, float("inf"), DELTA / len(THETA_HI_CHAINS)
    for hi in THETA_HI_CHAINS:
        for lo in range(hi, THETA_LO_MIN - 1, -1):
            pol = policy("route3", (hi, lo))
            if not certified(train, pol, delta):
                break
            c = sum(cost(pol(r)) for r in train) / len(train)
            if c < best_cost:
                best, best_cost = (hi, lo), c
    return best


def cross_validate(table):
    spks = sorted({r["spk"] for r in table})
    random.Random(SEED).shuffle(spks)
    fold = {s: i % FOLDS for i, s in enumerate(spks)}
    res = {}
    for name in POLICIES:
        oof, chosen = [], []
        for f in range(FOLDS):
            train = [r for r in table if fold[r["spk"]] != f]
            p = select_route(train) if name == "route3" else (select_single(train, name) if name.endswith("_theta") else None)
            calibrated = name == "route3" or name.endswith("_theta")
            chosen.append(p)
            pol = policy("reference", None) if (calibrated and p is None) else policy(name, p)
            oof += [(r, pol(r)) for r in table if fold[r["spk"]] == f]
        res[name] = {"failures": sum(int(r["fail"][k]) for r, k in oof), "n": len(oof),
                     "mean_nfe": sum(cost(k) for _, k in oof) / len(oof), "chosen": chosen,
                     "routed": {o: sum(k == o for _, k in oof) for o in ("plain_4", "vswap_4", "plain_8")}}
    return res


def evaluate(table, div, cv):
    """The preregistered criteria; a criterion needing missing data is None."""
    noisy, clean = paired_failures(table, "plain_4", "vswap_4", NOISY), paired_failures(table, "plain_4", "vswap_4", ("clean",))
    mech = metric_diff(table, "vswap_4", "rswap_4", "similarity", NOISY)
    c = {"C1_noisy_failures": noisy["b"] <= FAILURE_DROP * noisy["a"] and noisy["b"] < noisy["a"] and noisy["p"] < P_MAX,
         "C2_clean_failures": clean["b"] <= clean["a"] + 1,
         "C3_voice_is_the_cause": mech["lo"] > 0}
    detail = {"noisy": noisy, "clean": clean, "similarity_vswap_minus_rswap_noisy": mech,
              "similarity_vswap_minus_plain4_noisy": metric_diff(table, "vswap_4", "plain_4", "similarity", NOISY),
              "similarity_vswap_minus_student_noisy": metric_diff(table, "vswap_4", "student4", "similarity", NOISY),
              "wer_vswap_minus_plain4_noisy": metric_diff(table, "vswap_4", "plain_4", "wer", NOISY)}
    if div:
        vs_student, vs_plain = cv_diff(div, "vswap_4", "student4"), cv_diff(div, "vswap_4", "plain_4")
        c["C4_diversity"] = vs_student["lo"] > 0 and vs_plain["lo"] > -MARGIN_CV
        detail.update({"cv_vs_student": vs_student, "cv_vs_plain4": vs_plain})
    else:
        c["C4_diversity"] = None
    a, b = cv["route3"], cv["snr_theta"]
    c["C5_beats_calibrated_snr"] = a["mean_nfe"] < b["mean_nfe"] and a["failures"] <= b["failures"]
    return {"criteria": c, "advance": all(v is True for v in c.values()), "detail": detail}


def _avg(values):
    values = list(values)
    return sum(values) / len(values) if values else None


def analyze(out, allow_partial=False, prereg_path=PREREG_PATH):
    out = Path(out)
    pre = check_prereg(prereg_path)
    th = gl.thresholds()
    table = build_table(load_stored(), rf.read_csv(out / "swap.csv", repair=True), th)
    div_path = out / "diversity.csv"
    div = rf.read_csv(div_path, repair=True) if div_path.exists() else []
    expected, expected_div = N_SPEAKERS * len(CONDS), DIV_PAIRS
    partial = len(table) < expected or len(div) < expected_div
    if partial and not allow_partial:
        raise SystemExit(f"{len(table)} of {expected} cases, {len(div)} of {expected_div} diversity pairs; finish the run or pass --allow_partial")
    names = ["student4", "plain_4", "plain_8"] + list(OUTS)
    cap = lambda v: min(1.0, v)
    res = {"prereg_sha256": pre["sha256"], "cases": len(table), "expected_cases": expected, "diversity_pairs": len(div),
           "expected_diversity_pairs": expected_div, "partial": partial, "passes": {n: cost(n) for n in names},
           "failures": {c: {n: sum(r["fail"][n] for r in table if r["cond"] == c) for n in names} for c in CONDS},
           "means": {c: {n: {"wer_capped": _avg(cap(r["m"][n]["wer"]) for r in table if r["cond"] == c),
                             "similarity": _avg(r["m"][n]["similarity"] for r in table if r["cond"] == c),
                             "utmos": _avg(r["m"][n]["utmos"] for r in table if r["cond"] == c)} for n in names} for c in CONDS},
           "cvf0": {o: _avg(float(r[f"cvf0_{o}"]) for r in div if not math.isnan(float(r[f"cvf0_{o}"]))) for o in DIV_OUTS} if div else {}}
    res["cross_validation"] = cross_validate(table) if len({r["spk"] for r in table}) >= FOLDS else None
    res["primary"] = evaluate(table, div, res["cross_validation"]) if res["cross_validation"] else None
    (out / "voice_swap_results.json").write_text(json.dumps(res, indent=2) + "\n", encoding="utf-8")
    (out / "VOICE_SWAP_REPORT.md").write_text(render(res), encoding="utf-8")
    print(f"Wrote {out / 'VOICE_SWAP_REPORT.md'}", flush=True)
    return res


def _word(v):
    return "n/a" if v is None else ("PASS" if v else "FAIL")


