"""Preliminary Colab T4 test of Voice-Swap Handover (EXP-020).

Teacher-guided sampling passes the teacher's whole endpoint estimate to the student. On noisy prompts
most Step-4 failures are speaker-similarity failures. Voice-Swap Handover keeps what changes over time
from the teacher and takes the per-band average over time, which carries overall tone and steady
noise, from one quick student draft. No model is trained; the released teacher and student are used:

  S = eps + g(eps, 0)                                  one student pass from its own noise (+1 forward pass)
  x = T - bandavg(T) + bandavg(S)                      on generated frames; prompt frames are unchanged
  student's normal restart then runs from x            (3 passes)

Prompt SNR chooses the route for each input, with cut-offs calibrated by Learn-Then-Test:
  SNR >= theta_hi             plain handover at Step 4   (13 passes)
  theta_lo <= SNR < theta_hi  Voice-Swap at Step 4       (14 passes)
  SNR < theta_lo              reference, Step 8          (21 passes)

Generated by this runner: vswap_4 and rswap_4, the reversed control (the student's time-varying part with
the teacher's averages). Reused without new synthesis: plain Steps 4 and 8 (EXP-018) and student only (EXP-017).

Data: the EXP-012 Quick set (60 development speakers x 6 conditions). Pitch diversity (CVf0, the DMOSpeech 2
measure): the first 20 development speakers, clean prompt, 20 seeds each. Development evidence only; the
criteria are frozen in preregistration.json before any synthesis.

Subcommands: freeze (write the preregistration once), smoke, run (resumable), analyze.
"""
