def cost(name):
    """Forward passes: 2 per guided teacher evaluation, 1 per student step, +1 for the student draft S."""
    if name == "student4":
        return 4
    base, k = name.rsplit("_", 1)
    return 2 * (int(k) + 1) + 3 + (1 if base in SWAP_OPS else 0)


# --------------------------------------------------------------------------- algorithm
def _clone(x):
    return x.clone() if hasattr(x, "clone") else x.copy()


def band_average(x):
    """Per-band average over time of an array shaped (frames, bands), keeping the frame axis."""
    return x.mean(dim=0, keepdim=True) if hasattr(x, "clone") else x.mean(axis=0, keepdims=True)


def voice_swap(T, S, plen):
    """x = T - bandavg(T) + bandavg(S) on generated frames: the teacher's time-varying part, the student's averages."""
    x = _clone(T)
    x[0, plen:, :] = T[0, plen:, :] - band_average(T[0, plen:, :]) + band_average(S[0, plen:, :])
    return x


def reverse_swap(T, S, plen):
    """Control: x = S - bandavg(S) + bandavg(T) on generated frames: the student's time-varying part, the teacher's averages."""
    x = _clone(T)
    x[0, plen:, :] = S[0, plen:, :] - band_average(S[0, plen:, :]) + band_average(T[0, plen:, :])
    return x


def swap_rms(T, S, plen):
    """Root-mean-square size of the change the swap makes to the band averages."""
    d = band_average(T[0, plen:, :]) - band_average(S[0, plen:, :])
    return float((d * d).mean()) ** 0.5


def handover_inputs(E, S, plen, names):
    """{name: handover input} for names like vswap_4, rswap_4 and plain_8."""
    out = {}
    for name in names:
        base, k = name.rsplit("_", 1)
        k = int(k)
        if base == "vswap":
            out[name] = voice_swap(E[k], S, plen)
        elif base == "rswap":
            out[name] = reverse_swap(E[k], S, plen)
        elif base == "plain":
            out[name] = E[k]
    return out


def student_sample(pipe, ctx):
    """One student pass at tau = 0 from noise that is independent of the teacher's: S = eps + g(eps, 0)."""
    torch, sampler = pipe.torch, pipe.sampler
    with torch.inference_mode():
        gen = sampler.make_local_generator((int(ctx["seed"]) + STUDENT_SAMPLE_OFFSET) % (2 ** 31 - 1), device=pipe.device)
        eps = torch.randn(ctx["y0"].shape, dtype=torch.float32, device=pipe.device, generator=gen)
        tt = torch.tensor([0.0], device=pipe.device, dtype=torch.float32)
        return eps + pipe.tts.generator(x=eps, cond=ctx["cond"], text=ctx["text_ids"], time=tt, drop_audio_cond=False, drop_text=False)


# ----------------------------------------------------------------------- pitch diversity
def f0_track(audio, sr=24000):
    """Frame-wise f0 in Hz (librosa pYIN); unvoiced frames are NaN."""
    import librosa
    return librosa.pyin(audio, fmin=F0_MIN, fmax=F0_MAX, sr=sr, frame_length=F0_FRAME, hop_length=F0_HOP)[0]


def cvf0(tracks, min_voiced=MIN_VOICED):
    """CVf0 across seeds, averaged over frames: per frame std/mean of f0 across the seeds that voice it.

    Tracks are cut to the shortest; a frame counts if at least min_voiced of the seeds (and at least 2) voice it.
    Returns (CVf0, share of frames kept)."""
    import numpy as np
    n = min(len(t) for t in tracks)
    a = np.stack([np.asarray(t[:n], dtype=float) for t in tracks])
    keep = (~np.isnan(a)).sum(axis=0) >= max(2, math.ceil(min_voiced * a.shape[0]))
    if not keep.any():
        return float("nan"), 0.0
    a = a[:, keep]
    return float(np.mean(np.nanstd(a, axis=0, ddof=1) / np.nanmean(a, axis=0))), float(keep.mean())


